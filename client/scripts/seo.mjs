// Pure helpers behind scripts/prerender.mjs (kept separate so they are unit-tested: scripts/seo.test.mjs).
import { OG_IMAGE, PUBLIC_ROUTES, SITE_NAME, absoluteUrl, fullTitleOf } from "../src/seo/routes.js";

const SEO_BLOCK = /<!-- seo:start[\s\S]*?<!-- seo:end -->/;

export const escapeAttr = (value) =>
  String(value).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
export const escapeText = (value) => String(value).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

/** JSON for a <script type="application/ld+json">: "<" is escaped so no text can ever close the tag. */
export const safeJson = (value) =>
  JSON.stringify(value).replace(/</g, "\\u003c").replace(/\u2028/g, "\\u2028").replace(/\u2029/g, "\\u2029");

/** Accepts https URLs (and http only for localhost, for local test builds). Returns it without a trailing slash. */
export function normalizeSiteUrl(raw) {
  const value = String(raw || "").trim().replace(/\/+$/, "");
  if (!value) throw new Error("VITE_SITE_URL is not set. Set it to your public address, e.g. https://remindme.example.com");
  let url;
  try {
    url = new URL(value);
  } catch {
    throw new Error(`VITE_SITE_URL is not a valid URL: ${value}`);
  }
  const local = url.hostname === "localhost" || url.hostname === "127.0.0.1";
  if (url.protocol !== "https:" && !(local && url.protocol === "http:")) {
    throw new Error(`VITE_SITE_URL must start with https:// (got ${value})`);
  }
  if (url.pathname !== "/" || url.search || url.hash) throw new Error(`VITE_SITE_URL must be an origin only, without a path (got ${value})`);
  return url.origin;
}

/** The head tags (title ... JSON-LD) of one public page. */
export function buildSeoBlock(path, siteUrl) {
  const meta = PUBLIC_ROUTES[path];
  if (!meta) throw new Error(`Unknown public route ${path}`);
  const title = fullTitleOf(meta);
  const url = absoluteUrl(siteUrl, path);
  const image = absoluteUrl(siteUrl, OG_IMAGE.path);
  const lines = [
    "<!-- seo:start (generated by scripts/prerender.mjs) -->",
    `<title>${escapeText(title)}</title>`,
    `<meta name="description" content="${escapeAttr(meta.description)}" />`,
    `<meta name="robots" content="index, follow" />`,
    `<link rel="canonical" href="${escapeAttr(url)}" />`,
    `<meta property="og:type" content="website" />`,
    `<meta property="og:site_name" content="${escapeAttr(SITE_NAME)}" />`,
    `<meta property="og:locale" content="en_US" />`,
    `<meta property="og:title" content="${escapeAttr(title)}" />`,
    `<meta property="og:description" content="${escapeAttr(meta.description)}" />`,
    `<meta property="og:url" content="${escapeAttr(url)}" />`,
    `<meta property="og:image" content="${escapeAttr(image)}" />`,
    `<meta property="og:image:type" content="image/png" />`,
    `<meta property="og:image:width" content="${OG_IMAGE.width}" />`,
    `<meta property="og:image:height" content="${OG_IMAGE.height}" />`,
    `<meta property="og:image:alt" content="${escapeAttr(OG_IMAGE.alt)}" />`,
    `<meta name="twitter:card" content="summary_large_image" />`,
    `<meta name="twitter:title" content="${escapeAttr(title)}" />`,
    `<meta name="twitter:description" content="${escapeAttr(meta.description)}" />`,
    `<meta name="twitter:image" content="${escapeAttr(image)}" />`,
    `<meta name="twitter:image:alt" content="${escapeAttr(OG_IMAGE.alt)}" />`,
  ];
  for (const data of meta.jsonLd || []) {
    lines.push(`<script type="application/ld+json">${safeJson(data)}</script>`);
  }
  lines.push("<!-- seo:end -->");
  return lines.join("\n    ");
}

/** Replaces the seo block of the built index.html. Throws if the markers are missing (so the build fails loudly). */
export function applySeoBlock(html, block) {
  if (!SEO_BLOCK.test(html)) throw new Error("index.html has no <!-- seo:start --> ... <!-- seo:end --> block");
  return html.replace(SEO_BLOCK, () => block); // function form: "$" in the text is never treated as a pattern
}

export function buildSitemap(siteUrl) {
  const urls = Object.entries(PUBLIC_ROUTES)
    .map(
      ([path, meta]) =>
        `  <url>\n    <loc>${escapeText(absoluteUrl(siteUrl, path))}</loc>\n    <priority>${meta.priority || "0.5"}</priority>\n  </url>`
    )
    .join("\n");
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`;
}

/**
 * Private pages are NOT listed under Disallow: a crawler that is not allowed to fetch a page can never see its
 * "noindex", so the page could still show up in results. They are served the noindex app shell instead.
 */
export function buildRobots(siteUrl) {
  return `User-agent: *\nAllow: /\n\nSitemap: ${absoluteUrl(siteUrl, "/sitemap.xml")}\n`;
}

/** Output file (relative to dist) for a public path. */
export const fileForPath = (path) => (path === "/" ? "index.html" : `${path.replace(/^\/|\/$/g, "")}/index.html`);
