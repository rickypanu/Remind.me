from datetime import datetime
from typing import Annotated, Literal

from pydantic import BaseModel, Field, PlainSerializer, field_validator, model_validator

from utils.recurrence import (
    normalize_weekdays,
    parse_end_date,
    parse_time_of_day,
)

from utils.timezone import as_ist  # noqa: E402

ScheduleType = Literal["once", "daily", "weekly"]

# Every timestamp the API SENDS is written in IST (e.g. 2026-10-24T21:30:00+05:30). It is the same instant the
# database holds (BSON dates are UTC internally and cannot carry an offset), just expressed the way the app shows it.
IstDatetime = Annotated[datetime, PlainSerializer(lambda value: as_ist(value).isoformat(), return_type=str, when_used="json")]


class TaskCreate(BaseModel):
    """
    Create a reminder.

    schedule_type:
      once    -> due_date is required (a specific date and time)
      daily   -> time_of_day ("HH:MM", IST) is required; due_date is calculated by the server
      weekly  -> time_of_day and weekdays (0 = Monday ... 6 = Sunday) are required
    ends_on ("YYYY-MM-DD", IST) optionally stops a daily / weekly series.
    """
    title: str = Field(min_length=1, max_length=200)
    description: str | None = Field(default=None, max_length=1000)
    category: str = Field(min_length=1, max_length=60)
    due_date: datetime | None = None
    status: str = "pending"

    schedule_type: ScheduleType = "once"
    time_of_day: str | None = None
    weekdays: list[int] = Field(default_factory=list)
    ends_on: str | None = None
    # Generated by the offline-first client. Lets the server ignore a retried create (idempotency).
    client_id: str | None = Field(default=None, max_length=64)

    @field_validator("title", "category")
    @classmethod
    def _strip_required(cls, v: str) -> str:
        v = v.strip()
        if not v:
            raise ValueError("must not be empty")
        return v

    @field_validator("description")
    @classmethod
    def _strip_description(cls, v: str | None) -> str | None:
        if v is None:
            return None
        v = v.strip()
        return v or None

    @model_validator(mode="after")
    def _validate_schedule(self):
        if self.schedule_type == "once":
            if self.due_date is None:
                raise ValueError("due_date is required for a one-time reminder")
            self.time_of_day, self.weekdays, self.ends_on = None, [], None
            return self

        if not self.time_of_day:
            raise ValueError("time_of_day (HH:MM) is required for daily and weekly reminders")
        t = parse_time_of_day(self.time_of_day)
        self.time_of_day = f"{t.hour:02d}:{t.minute:02d}"

        if self.schedule_type == "weekly":
            self.weekdays = normalize_weekdays(self.weekdays)
            if not self.weekdays:
                raise ValueError("Pick at least one weekday for a weekly reminder")
        else:
            self.weekdays = []

        if self.ends_on:
            parse_end_date(self.ends_on)
        else:
            self.ends_on = None
        return self


class TaskUpdate(BaseModel):
    """
    Partial edit (PUT /tasks/{id}). Only fields that are sent are changed.
      once       -> due_date may change
      daily/week -> time_of_day may change (the next due date is recalculated)
    """
    title: str | None = Field(default=None, min_length=1, max_length=200)
    description: str | None = Field(default=None, max_length=1000)
    category: str | None = Field(default=None, min_length=1, max_length=60)
    due_date: datetime | None = None
    time_of_day: str | None = None

    @field_validator("title", "category")
    @classmethod
    def _strip_required(cls, v: str | None) -> str | None:
        if v is None:
            return None
        v = v.strip()
        if not v:
            raise ValueError("must not be empty")
        return v

    @field_validator("description")
    @classmethod
    def _strip_description(cls, v: str | None) -> str | None:
        if v is None:
            return None
        return v.strip() or None


class TaskStatusUpdate(BaseModel):
    status: Literal["pending", "completed"]


class TaskResponse(BaseModel):
    id: str
    user_id: str
    title: str
    description: str | None = None
    category: str
    due_date: IstDatetime | None = None
    status: str = "pending"

    schedule_type: ScheduleType = "once"
    time_of_day: str | None = None
    weekdays: list[int] = Field(default_factory=list)
    ends_on: str | None = None
    schedule_label: str = "One time"
    completed_count: int = 0
    last_completed_at: IstDatetime | None = None
    client_id: str | None = None
    updated_at: IstDatetime | None = Field(default=None, description="Last change (IST): the delta-sync clock")


class TaskStatusResponse(BaseModel):
    message: str
    recurring: bool = False
    next_due: IstDatetime | None = None


class TaskTombstone(BaseModel):
    """A deleted reminder, as reported by delta sync. The content is gone; only the fact of the delete remains."""

    id: str
    deleted_at: IstDatetime | None = None
    updated_at: IstDatetime | None = None


class TaskSyncPage(BaseModel):
    """One page of ``GET /v1/tasks``.

    items        reminders created or changed since the cursor (full content)
    deleted      reminders deleted since the cursor (remove them locally)
    next_cursor  pass it back as ``?cursor=`` for the next page / the next poll. Always present.
    has_more     True: ask again NOW with next_cursor. False: you are up to date.
    snapshot     True when this is a full download (no cursor was sent). When the last page of a snapshot
                 arrives (has_more is False) delete every local reminder the snapshot did not mention.
    server_time  the server clock when the page was made (informational)
    """

    items: list[TaskResponse]
    deleted: list[TaskTombstone] = Field(default_factory=list)
    next_cursor: str
    has_more: bool
    snapshot: bool
    server_time: IstDatetime


class TaskStatsResponse(BaseModel):
    """``GET /v1/tasks/stats``: numbers for the dashboard's motivation card (IST calendar days)."""

    streak: int = Field(ge=0, description="Consecutive days with at least one completion, ending today or yesterday")
    best_streak: int = Field(ge=0, description="Longest streak in the last 400 days")
    completed_today: int = Field(ge=0)
